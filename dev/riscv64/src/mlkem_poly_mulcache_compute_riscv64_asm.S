/*
 * For each pair (p0, p1) of coefficients of p in NTT domain, computes
 * cache = zeta_i * p1 mod q, where zeta_i is the twiddle of the pair; see
 * rv64v_basemul.inc.
 *
 * Uses Barrett multiplication [@NeonNTT]: for a twiddle z with twisted
 * constant z' = round(z * 2^15 / q),
 *
 *   p1 * z mod q  ~  p1 * z - q * round(p1 * z' / 2^15)
 *
 * computed with vmul, vsmul (with vxrm = rnu) and vnmsac. The result is
 * congruent to p1 * z mod q and bounded by q * (|p1| / 2^16 + 1/2) < q in
 * absolute value.
 *
 * Table: the 128 twiddles zeta_i, followed by their twisted constants.
 *
 * Vector-length agnostic: works for any VLEN. Uses register groups of 2
 * (LMUL=2). VLMAX for e16,m2 is a power of 2, so it either divides 128 or
 * exceeds it, and the VL is the same in every iteration.
 */

#define out             a0
#define in              a1
#define zetas           a2
#define count           a3
#define zetas_twisted   a4
#define vl              t0
#define modulus         t1
#define stride          t2
#define cache_stride    t3

#define p0v             v8  /* register group of 2 */
#define p1v             v10 /* register group of 2; follows p0v */
#define zv              v12
#define ztv             v14
#define tmp             v16

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLK_ASM_NAMESPACE(poly_mulcache_compute_riscv64_asm)
MLK_ASM_FN_SYMBOL(poly_mulcache_compute_riscv64_asm)

        csrwi       vxrm, 0                // round-to-nearest-up
        li          modulus, MLKEM_Q
        li          count, (MLKEM_N / 2)   // number of pairs
        addi        zetas_twisted, zetas, MLKEM_N

        vsetvli     vl, count, e16, m2, ta, ma
        slli        stride, vl, 2          // bytes per VL pairs
        slli        cache_stride, vl, 1    // bytes per VL cache entries

mlk_poly_mulcache_compute_riscv64_loop:
        vlseg2e16.v p0v, (in)
        vle16.v     zv, (zetas)
        vle16.v     ztv, (zetas_twisted)

        vsmul.vv    tmp, p1v, ztv
        vmul.vv     p1v, p1v, zv
        vnmsac.vx   p1v, modulus, tmp
        vse16.v     p1v, (out)

        add         in, in, stride
        add         out, out, cache_stride
        add         zetas, zetas, cache_stride
        add         zetas_twisted, zetas_twisted, cache_stride
        sub         count, count, vl
        bnez        count, mlk_poly_mulcache_compute_riscv64_loop

        ret
.option pop

MLK_ASM_FN_SIZE(poly_mulcache_compute_riscv64_asm)

