/*
 * Multiplies each coefficient by 2^16 mod q, using Barrett multiplication
 * [@NeonNTT]: for a constant c with twisted constant c' = round(c * 2^15 / q),
 *
 *   x * c mod q  ~  x * c - q * round(x * c' / 2^15)
 *
 * computed with vmul, vsmul (with vxrm = rnu) and vnmsac. The result is
 * congruent to x * c mod q and bounded by q * (|x| / 2^16 + 1/2) <= q in
 * absolute value. vsmul cannot saturate, as |c'| < 2^15.
 *
 * Vector-length agnostic: works for any VLEN. Uses register groups of 4
 * (LMUL=4). VLMAX for e16,m4 is a power of 2, so it either divides 256 or
 * exceeds it. Hence a single vsetvli with AVL = 256 yields a VL that is
 * used unchanged for every iteration.
 */

#define ptr             a0
#define count           a1
#define vl              t0
#define modulus         t1
#define factor          t2
#define factor_twisted  t3
#define stride          t4

#define data            v0
#define tmp             v4

/* Barrett multiplication of \a by the constant c with twisted constant
 * c_twisted, in place, using \t as temporary. */
.macro barrett_mul_const a, t, c, c_twisted
        vsmul.vx    \t, \a, \c_twisted
        vmul.vx     \a, \a, \c
        vnmsac.vx   \a, modulus, \t
.endm

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLK_ASM_NAMESPACE(poly_tomont_riscv64_asm)
MLK_ASM_FN_SYMBOL(poly_tomont_riscv64_asm)

        csrwi       vxrm, 0                // round-to-nearest-up
        li          modulus, MLKEM_Q
        li          factor, -1044          // 2^16 mod q (signed)
        li          factor_twisted, -10276 // round(-1044 * 2^15 / q)
        li          count, MLKEM_N

        vsetvli     vl, count, e16, m4, ta, ma
        slli        stride, vl, 1

mlk_poly_tomont_riscv64_loop:
        vle16.v     data, (ptr)
        barrett_mul_const data, tmp, factor, factor_twisted
        vse16.v     data, (ptr)

        add         ptr, ptr, stride
        sub         count, count, vl
        bnez        count, mlk_poly_tomont_riscv64_loop

        ret
.option pop

MLK_ASM_FN_SIZE(poly_tomont_riscv64_asm)

