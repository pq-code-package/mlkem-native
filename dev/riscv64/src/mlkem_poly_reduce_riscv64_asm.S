/*
 * Vector-length agnostic: works for any VLEN. Uses register groups of 4
 * (LMUL=4). VLMAX for e16,m4 is a power of 2, so it either divides 256 or
 * exceeds it. Hence a single vsetvli with AVL = 256 yields a VL that is
 * used unchanged for every iteration.
 */

#define ptr             a0
#define count           a1
#define vl              t0
#define modulus         t1
#define barrett_const   t2
#define round_const     t3
#define stride          t4

#define data            v0
#define tmp             v4

/* Barrett reduction of \a to (-q/2, q/2], using \t as temporary:
 *   t = ((a * 20159) >> 16 + 2^9) >> 10   (= round(a / q))
 *   a = a - t * q */
.macro barrett_reduce a, t
        vmulh.vx    \t, \a, barrett_const
        vadd.vx     \t, \t, round_const
        vsra.vi     \t, \t, 10
        vmul.vx     \t, \t, modulus
        vsub.vv     \a, \a, \t
.endm

/* Add q to \a if negative, using \t as temporary. */
.macro signed_to_unsigned a, t
        vsra.vi     \t, \a, 15
        vand.vx     \t, \t, modulus
        vadd.vv     \a, \a, \t
.endm

.text
.option push
.option norvc
.option norelax
.balign 4
.global MLK_ASM_NAMESPACE(poly_reduce_riscv64_asm)
MLK_ASM_FN_SYMBOL(poly_reduce_riscv64_asm)

        li          modulus, MLKEM_Q
        li          barrett_const, 20159   // round(2^26 / q)
        li          round_const, 512       // 2^9
        li          count, MLKEM_N

        vsetvli     vl, count, e16, m4, ta, ma
        slli        stride, vl, 1

mlk_poly_reduce_riscv64_loop:
        vle16.v     data, (ptr)
        barrett_reduce data, tmp
        signed_to_unsigned data, tmp
        vse16.v     data, (ptr)

        add         ptr, ptr, stride
        sub         count, count, vl
        bnez        count, mlk_poly_reduce_riscv64_loop

        ret
.option pop

MLK_ASM_FN_SIZE(poly_reduce_riscv64_asm)

